//! Traffic insights (18.16.0): who visits — people, AI agents, bots —
//! worked out by rws from each request, for the admin UI's Traffic page.
//!
//! This first part is the classifier, [`classify`]: from the client's
//! address, User-Agent and path it names what kind of client this is, using
//! - the IP ranges Google, Bing, Apple, DuckDuckGo, OpenAI, Perplexity and
//!   Common Crawl publish for their crawlers (a match is *verified*; a
//!   User-Agent that claims one of them from elsewhere is *spoofed*);
//! - [ai.robots.txt](https://github.com/ai-robots-txt/ai.robots.txt)'s AI
//!   agents and [crawler-user-agents](https://github.com/monperrus/crawler-user-agents)'
//!   bot patterns (both MIT, bundled, regenerated by `ci/gen_bot_lists.py`);
//! - requests only scanners make (`/.env`, `/.git/config`, `/wp-login.php`…).
//!
//! A browser User-Agent that matches none of them is a [`Kind::Browser`]:
//! whether it's a person is decided later, by whether that client loads the
//! page's assets as a browser does.

