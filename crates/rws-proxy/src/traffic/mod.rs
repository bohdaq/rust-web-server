/// Count one finished request (called with the access log line, whatever
/// the log format).
#[doc(hidden)]
pub fn observe(request: &crate::request::Request, response: &crate::response::Response, ip: std::net::IpAddr) {
    if !enabled() {
        return;
    }
    let header = |name: &str| request.header(name).map(|h| h.value.as_ref()).filter(|v: &&str| !v.is_empty());
    let content_type = response
        .content_range_list
        .first()
        .map(|c| c.content_type.as_str())
        .or_else(|| response.headers.iter().find(|h| h.name.eq_ignore_ascii_case("content-type")).map(|h| h.value.as_ref()));
    record::record(&record::Hit {
        ip,
        host: header("host").unwrap_or(""),
        user_agent: header("user-agent"),
        referer: header("referer"),
        method: &request.method,
        path: &request.request_uri,
        status: response.status_code,
        content_type,
        headers: &request.headers,
        now: record::now(),
    });
}

/// Start counting, with the saved counts loaded and saved again every five
/// minutes (when `persist` gives a file). The `rws` binary calls this when
/// the admin API is on and `[traffic] enabled` isn't `false`.
pub fn start() {
    if enabled() {
        return;
    }
    enable();
    // Decode the country table now rather than on the first visitor's request.
    let _ = std::thread::Builder::new().name("rws-traffic-geo".to_string()).spawn(|| {
        geo::table();
    });
    start_store();
    // Before loading the saved counts, so the configured sites keep slots.
    #[cfg(not(target_arch = "wasm32"))]
    configure_sites(&std::fs::read_to_string(crate::proxy_config::config_file_path()).unwrap_or_default());
    let Some(path) = config::persist_path() else { return };
    persist::load(&path);
    let _ = std::thread::Builder::new().name("rws-traffic".to_string()).spawn(move || loop {
        std::thread::sleep(std::time::Duration::from_secs(300));
        if let Err(e) = persist::save(&path) {
            eprintln!("traffic: can't save {}: {e}", path.display());
        }
    });
}

/// Count the sites `toml`'s routes match (`[[route]] match.host`) on
/// their own and list them first ([`record::set_configured_hosts`]).
#[cfg(not(target_arch = "wasm32"))]
pub fn configure_sites(toml: &str) {
    let config = crate::proxy_config::ProxyConfig::from_str(toml);
    record::set_configured_hosts(config.routes.iter().filter_map(|r| r.match_.host.clone()));
}

/// Connect to `[traffic] database_url_env`'s PostgreSQL, when set.
fn start_store() {
    let Some(url) = config::database_url() else { return };
    #[cfg(feature = "model-postgres")]
    match store::start(&url) {
        Ok(()) => println!("traffic: writing page views to PostgreSQL."),
        Err(e) => eprintln!("traffic: can't use the traffic database: {e}; counting without it"),
    }
    #[cfg(not(feature = "model-postgres"))]
    {
        let _ = url;
        eprintln!("traffic: [traffic] database_url_env is set, but this rws is built without the model-postgres feature; counting without it");
    }
}

/// Save the counts now (at shutdown).
pub fn save() {
    #[cfg(feature = "model-postgres")]
    store::stop();
    if let (true, Some(path)) = (enabled(), config::persist_path()) {
        if let Err(e) = persist::save(&path) {
            eprintln!("traffic: can't save {}: {e}", path.display());
        }
    }
}

