/// What an extractor sees: the request, the route's parameters, the
/// connection and the app's state.
pub struct RequestParts<'a, S> {
    pub request: &'a Request,
    pub params: &'a PathParams,
    pub connection: &'a ConnectionInfo,
    pub state: &'a Arc<S>,
    /// The route parameters the handler's [`Path`] argument takes, in the
    /// order it takes them (set by the route macro).
    pub path_names: &'static [&'static str],
}

/// A typed handler argument: built from the [`RequestParts`], or a
/// ready-to-send rejection.
///
/// Every [`FromRequest`] type is one, so `#[derive(FromRequest)]` structs
/// and `Validated<T>` work as arguments too.
pub trait FromRequestParts<S>: Sized {
    fn from_request_parts(parts: &RequestParts<'_, S>) -> Result<Self, Response>;
}

impl<S, T: FromRequest> FromRequestParts<S> for T {
    fn from_request_parts(parts: &RequestParts<'_, S>) -> Result<Self, Response> {
        T::from_request(parts.request)
    }
}

/// The app's shared state (`App::with_state(state)`): a clone of its `Arc`.
///
/// `State(db): State<Db>` in a handler's arguments; `&Db` works too.
pub struct State<S>(pub Arc<S>);

impl<S> Clone for State<S> {
    fn clone(&self) -> Self {
        State(Arc::clone(&self.0))
    }
}

impl<S> std::ops::Deref for State<S> {
    type Target = S;
    fn deref(&self) -> &S {
        &self.0
    }
}

impl<S> FromRequestParts<S> for State<S> {
    fn from_request_parts(parts: &RequestParts<'_, S>) -> Result<Self, Response> {
        Ok(State(Arc::clone(parts.state)))
    }
}

#[cfg(feature = "serde")]
