/// A route's method and pattern, generated by `#[get("/path")]` & co.
pub trait RouteSpec {
    const METHOD: &'static str;
    const PATTERN: &'static str;
}

/// A typed handler for apps with state `S`, made by the route macros from a
/// function whose arguments are extractors. Register it with `.route(h)`.
pub trait Handler<S>: RouteSpec + Send + Sync + 'static {
    /// Extract the arguments, call the function and turn its value into a
    /// [`Response`] (or answer with the first argument's rejection).
    fn handle(&self, request: &Request, params: &PathParams, connection: &ConnectionInfo, state: &Arc<S>) -> Response;
}

/// The future an [`AsyncHandler`] returns.
pub type HandlerFuture = Pin<Box<dyn Future<Output = Response> + Send + 'static>>;

/// A typed handler for `AsyncAppWithState` (`http2`): the route macros make
/// one from an `async fn`, and from every sync typed handler too.
pub trait AsyncHandler<S>: RouteSpec + Send + Sync + 'static {
    fn handle_async(&self, request: Request, params: PathParams, connection: ConnectionInfo, state: Arc<S>) -> HandlerFuture;
}

/// An extractor's rejection: problem details (or text, with
/// `error_format = "text"`) carrying the usual response headers.
pub(crate) fn rejection(request: &Request, status: &StatusCodeReasonPhrase, detail: &str) -> Response {
    crate::error::problem::with_headers(status, detail, detail, Some(Header::get_header_list(request)))
}

